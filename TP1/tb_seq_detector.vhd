library ieee;
use ieee.std_logic_1164.all;

entity tb_seq_detector is
end entity;

architecture sim of tb_seq_detector is
    constant CLK_PERIOD : time := 10 ns;

    -- Signals match DUT ports
    signal clk      : std_logic := '0';
    signal rst      : std_logic := '1';
    signal din      : std_logic := '0';
    signal detect   : std_logic;
    
    procedure apply_reset(
        signal rst_in : out std_logic;
        signal clk_in : in std_logic
    ) is
    begin
        -- reset DUT to known state
        rst_in <= '1';
        wait until rising_edge(clk_in); -- for synchronous reset
        wait for 1 ns;
        rst_in <= '0';
    end procedure;
begin
    -- clock generated by simple toggle assignment
    clk <= not clk after CLK_PERIOD / 2;

    dut: entity work.seq_detector
        port map(
            clk => clk,
            rst => rst,
            din => din,
            detect => detect
        );
        
    stim: process
    begin
        -- Assign input `din`, wait until it is sampled on rising edges of `clk`,
        -- then assert expected output `detect`.

        -- Scenario 1: almost detection (110110), should never detect
        apply_reset(rst, clk);
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        -- Scenario 2: almost detection (11001011), should never detect
        apply_reset(rst, clk);
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        -- Scenario 3: normal detection (11011011), detect on last bit
        apply_reset(rst, clk);
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '1' report "Normal detection failed" severity error;
        -- Scenario 4: overlap detection ("+011), detect on last bit
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '1' report "Overlapping detection failed" severity error;
        -- Scenario 5: overlap detection ("+1011011), detect on last bit
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '0'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '0' severity error;
        din <= '1'; wait until rising_edge(clk); wait for 1 ns; assert  detect = '1' report "Overlapping detection failed" severity error;
        wait for CLK_PERIOD*3;
        assert false report "Simulation finished successfully" severity failure;
    end process;
end architecture sim;            
        
library ieee;
use ieee.std_logic_1164.all;

entity tb_cipher_lfsr is
end entity;

architecture sim of tb_cipher_lfsr is
    constant CLK_PERIOD : time := 10 ns;

    signal clk          : std_logic := '0';
    signal rst          : std_logic := '1';
    signal enc_enable   : std_logic := '0';
    signal dec_enable   : std_logic := '0';
    signal din          : std_logic := '0';
    signal dec_in       : std_logic := '0';
    signal enc_out      : std_logic;
    signal dec_out      : std_logic;
    signal enc_ks       : std_logic;
    signal dec_ks       : std_logic;

    -- input sequence
    constant in_seq    : std_logic_vector(0 to 7) := "10110110";
begin
    -- clock generated by simple toggle assignment
    clk <= not clk after CLK_PERIOD / 2;

    -- Two identical ciphers are chained (encrypt then decrypt) to
    -- verify that the decrypted output matches the original input after two cycles of latency
    enc_dut: entity work.stream_cipher
    port map(
        clk => clk,
        rst => rst,
        enable => enc_enable,
        din => din,
        dout => enc_out,
        key_bit => enc_ks
        );
    -- Second cipher instance decrypts the first by using the same keystream.
    dec_dut: entity work.stream_cipher
        port map(
            clk => clk,
            rst => rst,
            enable => dec_enable,
            din => dec_in,
            dout => dec_out,
            key_bit => dec_ks
        );
    
    stim: process
    begin
        -- apply synchronous reset long enough for all blocks to initialize
        rst <= '1';
        wait until falling_edge(clk);
        wait until falling_edge(clk);
        wait for 1 ns;
        rst <= '0';

        for i in 0 to in_seq'length+1 loop
            -- Drive din and enable so they are stable before the rising edge
            wait until falling_edge(clk);
            dec_in <= enc_out;
            if i < in_seq'length then
                din <= in_seq(i);
            -- disable to pause the LFSR and hold outputs when no valid data is present
            elsif i = in_seq'length then
                enc_enable <= '0';
            else
                dec_enable <= '0';
            end if;
            case i is
                when 0 =>
                    enc_enable <= '1';
                when 1 =>
                    dec_enable <= '1';
                when others =>
                    wait for 1 ns;
                    assert dec_out = in_seq(i-2) report "Decrypted output did not match the input after two cycles" severity error;
            end case;
        end loop;
        
        wait for CLK_PERIOD*3;
        assert false report "Simulation finished successfully" severity failure;
    end process;
end architecture sim;            
